-- Enterprise mock: reviews, one record per logical loss, idempotency keys, and audit.
-- seq on reviews replaces SQLite rowid so "latest pending review" is stable.
-- Callers insert reviews by column name so the identity column can fill itself.

CREATE TABLE IF NOT EXISTS {{mock}}.reviews (
  id text PRIMARY KEY,
  case_id text,
  draft text,
  hash text,
  status text,
  reviewer text,
  seq bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE IF NOT EXISTS {{mock}}.records (
  id text PRIMARY KEY,
  case_id text NOT NULL UNIQUE,
  draft text NOT NULL,
  review_id text NOT NULL
);

CREATE TABLE IF NOT EXISTS {{mock}}.keys (
  key text PRIMARY KEY,
  hash text NOT NULL,
  response text NOT NULL
);

CREATE TABLE IF NOT EXISTS {{mock}}.calls (
  case_id text NOT NULL,
  tool text NOT NULL,
  n integer NOT NULL,
  PRIMARY KEY (case_id, tool)
);

CREATE TABLE IF NOT EXISTS {{mock}}.audit (
  seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at text NOT NULL,
  event text NOT NULL,
  case_id text,
  detail text
);
