-- Draft body and hash are immutable. Status, review id, and outcome may change.
-- seq orders "latest draft" the way SQLite rowid did.

CREATE TABLE IF NOT EXISTS {{output}}.drafts (
  draft_id text PRIMARY KEY,
  case_id text NOT NULL,
  input_revision integer,
  draft_json text NOT NULL,
  draft_hash text NOT NULL,
  status text NOT NULL,
  created_at text NOT NULL,
  review_id text,
  outcome text,
  seq bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE INDEX IF NOT EXISTS drafts_case_created ON {{output}}.drafts (case_id, created_at DESC, seq DESC);

CREATE OR REPLACE FUNCTION {{output}}.reject_draft_body_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.draft_json IS DISTINCT FROM OLD.draft_json
     OR NEW.draft_hash IS DISTINCT FROM OLD.draft_hash THEN
    RAISE EXCEPTION 'draft_json and draft_hash are immutable';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS drafts_body_immutable ON {{output}}.drafts;
CREATE TRIGGER drafts_body_immutable
BEFORE UPDATE ON {{output}}.drafts
FOR EACH ROW EXECUTE FUNCTION {{output}}.reject_draft_body_change();
