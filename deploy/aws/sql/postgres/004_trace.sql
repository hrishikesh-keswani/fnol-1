-- Hash-chained flight recorder. seq is the total order; it is not part of the hash.
-- Writers take an advisory lock, read the latest event_hash, then insert.

CREATE TABLE IF NOT EXISTS {{trace}}.trace_events (
  event_id text PRIMARY KEY,
  trace_id text NOT NULL,
  span_id text NOT NULL,
  parent_span_id text,
  case_id text,
  input_revision integer,
  draft_id text,
  step text NOT NULL,
  actor text NOT NULL,
  rule_version text,
  started_at text NOT NULL,
  duration_ms integer,
  attempt integer,
  status text NOT NULL,
  error_code text,
  mock_http_status integer,
  input_sha256 text,
  output_sha256 text,
  model_id text,
  input_tokens integer,
  output_tokens integer,
  shadow_narrative text,
  shadow_safety_status text,
  injection_field_status text,
  injection_model_status text,
  event text,
  prev_hash text,
  event_hash text,
  seq bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE INDEX IF NOT EXISTS trace_events_seq ON {{trace}}.trace_events (seq DESC);

CREATE OR REPLACE FUNCTION {{trace}}.reject_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END;
$$;

DROP TRIGGER IF EXISTS trace_events_no_update ON {{trace}}.trace_events;
CREATE TRIGGER trace_events_no_update
BEFORE UPDATE ON {{trace}}.trace_events
FOR EACH ROW EXECUTE FUNCTION {{trace}}.reject_append_only();

DROP TRIGGER IF EXISTS trace_events_no_delete ON {{trace}}.trace_events;
CREATE TRIGGER trace_events_no_delete
BEFORE DELETE ON {{trace}}.trace_events
FOR EACH ROW EXECUTE FUNCTION {{trace}}.reject_append_only();
